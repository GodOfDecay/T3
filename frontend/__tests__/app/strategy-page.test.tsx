/**
 * Phase F — the Migration Strategy page (research §6.4), rendering what the BACKEND produces for two
 * unrelated systems (`fixtures.json` → `migration_plan` = ClaimTrack, `migration_plan_payroll` =
 * Payroll; regenerated by help/Track-3/tools/regen_view_fixtures.py, never hand-edited).
 *
 *   - the page: the access gate, no legacy-code controls (this agent works from documents), the
 *     stub is gone;
 *   - sign-off: the producer is told why not; the hand-over names Equivalence Testing;
 *   - the ledger panel says what approval does, before and after, in every version state;
 *   - the view: timeline with the brief's dates, waves with entry/exit/rollback, criteria with their
 *     normalization, baselines with late ones flagged, every computed calendar conflict with whether
 *     it was reported and resolved, the order it started from (a cycle shown), effort as an estimate.
 */

